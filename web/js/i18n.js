const STORAGE_KEY = 'powerdiag-obi-lang';

function detect() {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved && STRINGS[saved]) return saved;

  const tag = (navigator.language || 'en').toLowerCase();
  if (tag.startsWith('ja')) return 'ja';
  if (tag.startsWith('ko')) return 'ko';
  if (tag.startsWith('vi')) return 'vi';
  if (tag.startsWith('th')) return 'th';
  /* Taiwan and Hong Kong read traditional characters; everything else Chinese
   * gets simplified. Guessing wrong here is jarring, so check the script and
   * region tags rather than just the language. */
  if (tag.startsWith('zh')) {
    return /hant|tw|hk|mo/.test(tag) ? 'zh-TW' : 'zh';
  }
  return 'en';
}

export const i18n = {
  lang: detect(),
  languages: Object.keys(STRINGS),
  t(key) {
    return STRINGS[this.lang][key] ?? STRINGS.en[key] ?? key;
  },
  set(lang) {
    if (!STRINGS[lang]) return;
    this.lang = lang;
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang;
  },
};
